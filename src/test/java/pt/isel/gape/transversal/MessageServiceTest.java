    @Test
    void futureScheduledMessageIsNotDeliveredUntilProcessingDate() throws Exception {
        LocalDateTime scheduledAt = LocalDateTime.of(2026, 2, 4, 18, 0);
        Message message = messageService.sendMessage(
                3L,
                null,
                AccessProfileType.TEACHER,
                new MessageCreateCommand(
                        190L,
                        3L,
                        null,
                        null,
                        "Scheduled",
                        "Future message",
                        MessageType.TEXT,
                        MessagePriority.NORMAL,
                        null,
                        scheduledAt,
                        List.of(4L)
                ),
                IP
        );

        assertEquals(MessageState.SCHEDULED, message.state());
        assertNull(message.sentAt());
        assertEquals(MessageReceiptState.PENDING, receiptState(4L, message.id()));
        assertNull(receiptDeliveredAt(4L, message.id()));
        assertEquals(0, messageService.processScheduledMessages(IP));

        MessageService dueService = new MessageService(
                connectionProvider,
                Clock.fixed(Instant.parse("2026-02-04T18:00:01Z"), ZoneOffset.UTC)
        );

        assertEquals(1, dueService.processScheduledMessages(IP));
        assertEquals("sent", messageState(message.id()));
        assertEquals(MessageReceiptState.DELIVERED, receiptState(4L, message.id()));
    }

