    @Test
    void marksDirectConversationReadInBulk() throws Exception {
        createDirectConversationWithUnreadMessages();

        int markedRead = messageService.markDirectConversationRead(
                4L,
                null,
                3L,
                LocalDateTime.of(2026, 2, 4, 18, 30),
                IP
        );

        assertEquals(2, markedRead);
        assertEquals(MessageReceiptState.READ, receiptState(4L, 9301L));
        assertEquals(MessageReceiptState.READ, receiptState(4L, 9302L));
        assertEquals(MessageReceiptState.DELIVERED, receiptState(3L, 9303L));
    }

    @Test
    void scheduleEventMessageUsesEventRecipientsAndContext() throws Exception {
        long channelId = createScheduleChannel();

        Message message = messageService.sendSystemMessage(
                null,
                null,
                null,
                new MessageCreateCommand(
                        channelId,
                        null,
                        null,
                        140L,
                        "Lesson reminder",
                        "Reminder generated from schedule",
                        MessageType.REMINDER,
                        MessagePriority.HIGH,
                        null,
                        LocalDateTime.of(2026, 2, 5, 17, 30),
                        List.of()
                ),
                IP
        );

        assertEquals(MessageState.SCHEDULED, message.state());
        assertEquals(MessageReceiptState.PENDING, receiptState(3L, message.id()));
        assertEquals(MessageReceiptState.PENDING, receiptState(4L, message.id()));
    }

    private static MessageCreateCommand textMessage(long channelId, long senderUserId, List<Long> recipients) {
        return new MessageCreateCommand(
                channelId,
                senderUserId,
                null,
                null,
                "Message",
                "Message body",
                MessageType.TEXT,
                MessagePriority.NORMAL,
                null,
                null,
                recipients
        );
    }

    private static MessageReceiptState receiptState(long userId, long messageId) throws SQLException {
        try (Connection connection = DatabaseTestSupport.openConnection();
             PreparedStatement statement = connection.prepareStatement("""
                     SELECT state
                     FROM receive_message
                     WHERE id_user = ?
                       AND id_message = ?
                     """)) {
            statement.setLong(1, userId);
            statement.setLong(2, messageId);
            try (ResultSet resultSet = statement.executeQuery()) {
                assertTrue(resultSet.next());
                return MessageReceiptState.fromDatabaseValue(resultSet.getString("state"));
            }
        }
    }

    private static LocalDateTime receiptDeliveredAt(long userId, long messageId) throws SQLException {
        try (Connection connection = DatabaseTestSupport.openConnection();
             PreparedStatement statement = connection.prepareStatement("""
                     SELECT delivered_at
                     FROM receive_message
                     WHERE id_user = ?
                       AND id_message = ?
                     """)) {
            statement.setLong(1, userId);
            statement.setLong(2, messageId);
            try (ResultSet resultSet = statement.executeQuery()) {
                assertTrue(resultSet.next());
                return resultSet.getTimestamp("delivered_at") == null
                        ? null
                        : resultSet.getTimestamp("delivered_at").toLocalDateTime();
            }
        }
    }

    private static String messageState(long messageId) throws SQLException {
        try (Connection connection = DatabaseTestSupport.openConnection();
             PreparedStatement statement = connection.prepareStatement("""
                     SELECT state
                     FROM message
                     WHERE id_message = ?
                     """)) {
            statement.setLong(1, messageId);
            try (ResultSet resultSet = statement.executeQuery()) {
                assertTrue(resultSet.next());
                return resultSet.getString("state");
            }
        }
    }

    private static long createScheduleChannel() throws SQLException {
        try (Connection connection = DatabaseTestSupport.openConnection();
             PreparedStatement channel = connection.prepareStatement("""
                     INSERT INTO channel (title, type, visibility, created_at, state)
                     VALUES ('Schedule Channel', 'system', 'participants', '2026-02-04 17:00:00', 'active')
                     """, java.sql.Statement.RETURN_GENERATED_KEYS)) {
            channel.executeUpdate();
            try (ResultSet generatedKeys = channel.getGeneratedKeys()) {
                generatedKeys.next();
                long channelId = generatedKeys.getLong(1);
                insertPair(connection, "associate_channel_class_group", "id_channel", "id_class_group", channelId, 50L);
                insertParticipation(connection, channelId, 3L, "teacher");
                insertParticipation(connection, channelId, 4L, "student");
                return channelId;
            }
        }
    }

    private static void createDirectConversationWithUnreadMessages() throws SQLException {
        try (Connection connection = DatabaseTestSupport.openConnection();
             PreparedStatement channelStatement = connection.prepareStatement("""
                     INSERT INTO channel (
                         id_channel, title, type, visibility, created_at, state
                     ) VALUES (
                         930, 'Unread direct message', 'message', 'participants', '2026-02-04 18:00:00', 'active'
                     )
                     """);
             PreparedStatement participationStatement = connection.prepareStatement("""
                     INSERT INTO participate_channel (
                         id_user, id_channel, role, joined_at, muted, state
                     ) VALUES
                         (3, 930, 'owner', '2026-02-04 18:00:00', 0, 'active'),
                         (4, 930, 'member', '2026-02-04 18:00:00', 0, 'active')
                     """);
             PreparedStatement messageStatement = connection.prepareStatement("""
                     INSERT INTO message (
                         id_message, id_channel, id_user_sender, id_parent_message, id_schedule_event_origin,
                         title, body, type, priority, attachment, created_at, updated_at, scheduled_at, sent_at, state
                     ) VALUES
                         (9301, 930, 3, NULL, NULL, 'First', 'First unread message.', 'text',
                          'normal', NULL, '2026-02-04 18:01:00', NULL, NULL, '2026-02-04 18:01:10', 'sent'),
                         (9302, 930, 3, NULL, NULL, 'Attachment', 'Attachment unread message.', 'attachment',
                          'normal', 'contents/pdf/unassigned/unread.pdf', '2026-02-04 18:02:00', NULL, NULL, '2026-02-04 18:02:10', 'sent'),
                         (9303, 930, 4, NULL, NULL, 'Sent', 'Message from current user.', 'text',
                          'normal', NULL, '2026-02-04 18:03:00', NULL, NULL, '2026-02-04 18:03:10', 'sent')
                     """);
             PreparedStatement receiptStatement = connection.prepareStatement("""
                     INSERT INTO receive_message (
                         id_user, id_message, delivered_at, read_at, state
                     ) VALUES
                         (4, 9301, '2026-02-04 18:01:20', NULL, 'delivered'),
                         (4, 9302, '2026-02-04 18:02:20', NULL, 'delivered'),
                         (3, 9303, '2026-02-04 18:03:20', NULL, 'delivered')
                     """)) {
            channelStatement.executeUpdate();
            participationStatement.executeUpdate();
            messageStatement.executeUpdate();
            receiptStatement.executeUpdate();
        }
    }

    private static void insertPair(
            Connection connection,
            String table,
            String firstColumn,
            String secondColumn,
            long first,
            long second
    ) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("""
                INSERT INTO %s (%s, %s)
                VALUES (?, ?)
                """.formatted(table, firstColumn, secondColumn))) {
            statement.setLong(1, first);
            statement.setLong(2, second);
            statement.executeUpdate();
        }
    }

    private static void insertParticipation(Connection connection, long channelId, long userId, String role)
            throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("""
                INSERT INTO participate_channel (id_user, id_channel, role, joined_at, muted, state)
                VALUES (?, ?, ?, '2026-02-04 17:00:00', 0, 'active')
                """)) {
            statement.setLong(1, userId);
            statement.setLong(2, channelId);
            statement.setString(3, role);
            statement.executeUpdate();
        }
    }
